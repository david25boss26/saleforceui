def test_data_validation():
    # 1. Valid record
    valid_recs = [
        {"customer_name": "John Doe", "email": "john@example.com", "product_code": "PRD_SLR_01", "budget": "5000", "event": "Launch"}
    ]
    validator = DataValidator()
    val_ok, val_fail = validator.validate(valid_recs, "india_launch")
    assert len(val_ok) == 1
    assert len(val_fail) == 0

    # 2. Invalid record (missing required name, invalid email, negative budget)
    invalid_recs = [
        {"customer_name": "", "email": "invalid-email", "product_code": "PRD_SLR_01", "budget": "-100", "event": "Launch"}
    ]
    val_ok, val_fail = validator.validate(invalid_recs, "india_launch")
    assert len(val_ok) == 0
    assert len(val_fail) == 1
    errs = val_fail[0]["_validation_errors"]
    rules = [e["rule"] for e in errs]
    assert "required" in rules
    assert "email_format" in rules
    assert "business_rule_>=" in rules

    # 3. Duplicate detection within the same batch
    dup_recs = [
        {"customer_name": "John", "email": "john@example.com", "product_code": "PRD_SLR_01", "event": "Launch"},
        {"customer_name": "John", "email": "john@example.com", "product_code": "PRD_SLR_01", "event": "Launch"}
    ]
    val_ok, val_fail = validator.validate(dup_recs, "india_launch")
    assert len(val_ok) == 1
    assert len(val_fail) == 1
    assert val_fail[0]["_is_duplicate"] is True

def test_pipeline_dry_run():
    # Run pipeline on our mock India form
    filepath = os.path.join(settings.SAMPLE_DATA_DIR, "sample_form_india.xlsx")
    
    db = SessionLocal()
    pipeline = ETLPipeline(db)
    try:
        summary = pipeline.run(filepath, "india_launch", dry_run=True)
        assert summary["status"] in ["SUCCESS", "PARTIAL_SUCCESS"]
        assert summary["received"] == 5
        assert summary["successful"] == 2 # Row 1 & Row 5 succeed (Row 5 fails in live loading, but succeeds in dry-run)
        # 3 fails (Row 2 lookup failure, Row 3 validation failure, Row 4 duplicate validation failure)
        assert summary["failed"] == 3
        assert summary["skipped"] == 1
    finally:
        db.close()
