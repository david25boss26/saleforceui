def test_form_normalization():
    # India form raw headers
    india_raw = [
        {"Name": "John Doe", "Email": "john@example.com", "Product": "PRD_SLR_01", "Budget_Code": "BDG_IND_2026", "Budget": "10000", "Checklist": "CHK_STD_01", "CRM_ID": "camp_india_01"}
    ]
    norm_res = FormNormalizer.normalize(india_raw, "india_launch")
    assert norm_res["source_name"] == "india_launch"
    assert norm_res["country"] == "India"
    assert norm_res["records"][0]["customer_name"] == "John Doe"
    assert norm_res["records"][0]["email"] == "john@example.com"
    assert norm_res["records"][0]["product_code"] == "PRD_SLR_01"
    assert norm_res["records"][0]["budget_code"] == "BDG_IND_2026"
    assert norm_res["records"][0]["budget"] == "10000"
    
    # UAE form raw headers
    uae_raw = [
        {"Full_Name": "Mohammed Ali", "Email_Address": "mohammed@example.ae", "Product_Code": "PRD_WND_02", "Budget_Code": "BDG_UAE_2026", "Allocated_Budget": "15000", "CRM_ID": "camp_uae_01"}
    ]
    norm_res_uae = FormNormalizer.normalize(uae_raw, "uae_launch")
    assert norm_res_uae["source_name"] == "uae_launch"
    assert norm_res_uae["country"] == "UAE"
    assert norm_res_uae["records"][0]["customer_name"] == "Mohammed Ali"
    assert norm_res_uae["records"][0]["email"] == "mohammed@example.ae"
    assert norm_res_uae["records"][0]["product_code"] == "PRD_WND_02"
    assert norm_res_uae["records"][0]["budget_code"] == "BDG_UAE_2026"
    assert norm_res_uae["records"][0]["budget"] == "15000"

